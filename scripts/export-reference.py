"""Regenerate public catalogs from packaged schemas and the actual SDK tools.

Run with the project installed: python scripts/export-reference.py
No source socket, store, credentials or network is used.
"""
import asyncio
import json
from pathlib import Path
from dot_herdr.actions import METHODS,method_details
from dot_herdr.endpoint import build,catalog
from dot_herdr.demo import SyntheticVerifier

ROOT=Path(__file__).resolve().parents[1]

def constraints_text(details):
 c=details['connector_constraints'];rules=c['explicit_targets'];parts=[]
 if rules['required']:parts.append('explicit '+', '.join(rules['required']))
 for group in rules['one_of_each']:parts.append('one of '+'/'.join(group))
 for path in rules['nonempty_arrays']:parts.append('nonempty '+path+' with explicit IDs')
 if c['absolute_paths']:parts.append('absolute '+', '.join(c['absolute_paths']))
 for key in ('timeout_ms','limit'):
  if key in c:
   b=c[key];parts.append(f"{key}: {b['minimum']}–{b['maximum']}, default{b['default']}")
 if 'match_event.event' in c:parts.append('match_event.event: pane_agent_status_changed only')
 if 'text' in c:parts.append('text ≤16KiB; input rules below')
 if 'keys' in c:parts.append('1–32 keys, 1–64 characters/key when supplied')
 if 'wait' in c:parts.append('prompt wait omitted/null')
 if details['access']=='events':parts.append('1–32 filters; ≤128KiB; no reconnect/replay')
 return '; '.join(parts) or 'Common limits below'

async def main():
 lines=['# Native Herdr coverage','','Herdr0.9.3, protocol22/schema1:102 methods;98 supported through19 MCP tools.',
        '32 queries and65 actions use the existing request adapter. `events.subscribe`',
        'uses a bounded dedicated socket through `collect_native_events`. Four methods',
        'require another transport and reject dispatch.','','## How to use this reference','',
        'Call `get_herdr_capabilities()` to check grants and discover methods. Supply',
        '`method` for its route, permissions, complete native input schema and extra',
        'connector constraints. Required native fields below are not the whole input:',
        'optional fields, enums and nested objects are in that schema. See',
        '[control examples](control.md) and [information layout](guidance.md).','',
        'All calls require `herdr:observe`. These session operations additionally need',
        '`session_users`; actions also require `herdr:control` and request-ID dedupe.',
        'All native params are limited to32KiB; unknown top-level fields reject.',
        'Explicit IDs are1–256characters; cwd alternatives are source-host paths.',
        'Prompt/send_text must be nonblank and ≤16KiB UTF8, with no U+0000–U+001F',
        'except tab/newline. For pane.send_input, nonempty text follows these rules;',
        'keys-only input is allowed. Supplied keys contain1–32 values of1–64characters',
        'and no U+0000–U+001F. Wait timeouts are finite; prompt wait is separate.',
        'Each write request ID is1–128characters; retain the ID for exact retries and',
        'inspect unknown outcomes before any new submission. Event collection opens',
        'one socket, with a connection timeout of10seconds in addition to its sample',
        'window. Native values are validated by Herdr. Unsupported methods cannot',
        'be dispatched, even though their schema is discoverable.','',
        'Generated by `scripts/export-reference.py` from packaged method data and',
        'the validation/discovery rules used by the endpoint.','',
        '| Native method | Route | Required native fields | Connector constraints | Notes |',
        '| --- | --- | --- | --- | --- |']
 for method in METHODS:
  d=method_details(method)
  route=d['tool'] or 'unsupported'
  required=', '.join(d['required']) or 'none'
  notes=d.get('reason',d.get('notes',''))
  row=[f'`{method}`',route,required,constraints_text(d),notes]
  lines.append('| '+' | '.join(v.replace('|','/') for v in row)+' |')
 lines+=['','Sources: installed `herdr api schema --json` and version-pinned',
         '[socket routing](https://github.com/herdrdev/herdr/blob/v0.9.3/src/api/server.rs),',
         '[application dispatch](https://github.com/herdrdev/herdr/blob/v0.9.3/src/app/api.rs) and',
         '[native waits](https://github.com/herdrdev/herdr/blob/v0.9.3/src/api/wait.rs).',
         'Coverage describes implemented adapters. Real writes and the complete',
         'OAuth/dot workflow remain unverified.','']
 (ROOT/'docs/native-coverage.md').write_text('\n'.join(lines))
 server=build(None,None,None,SyntheticVerifier(),'https://auth.example.invalid','https://connector.example.invalid/mcp')
 data={'classification':'implemented_catalog','protocol':'2026-07-28','store_schema':2,
       'events':catalog(),'tools':[t.model_dump(by_alias=True,mode='json') for t in await server.list_tools()]}
 (ROOT/'docs/implemented-schemas.json').write_text(json.dumps(data,indent=2)+'\n')
 print('Exported102 native method entries and',len(data['tools']),'MCP tools; no live connection.')

if __name__=='__main__':asyncio.run(main())
